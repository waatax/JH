const teachingPath = 'dist/teaching.js';
let content = fs.readFileSync(teachingPath, 'utf8');

// Find insertion point right after the last table definition and before exports
// Let's see: we can append each unit's add call right before `export const teachingTables = tables;`
const targetMarker = 'export const teachingTables = tables;';
if (!content.includes(targetMarker)) {
  console.error('Target marker not found in dist/teaching.js!');
  process.exit(1);
}

const unitEntries = Object.entries(bespokeTables);
console.log(`Checking ${unitEntries.length} bespoke unit tables for 3-column rows...`);
for (const [id, data] of unitEntries) {
  if (!data.title || typeof data.title !== 'string') throw new Error(`Missing title for ${id}`);
  for (const [rIdx, row] of data.rows.entries()) {
    if (!Array.isArray(row) || row.length !== 3) {
      throw new Error(`Unit ${id} row ${rIdx} has invalid length ${row?.length}: ${JSON.stringify(row)}`);
    }
    for (const cell of row) {
      if (typeof cell !== 'string' || cell.trim().length === 0) {
        throw new Error(`Unit ${id} row ${rIdx} has empty cell`);
      }
    }
  }
}
console.log(`All ${unitEntries.length} tables verified! Injecting into ${teachingPath}...`);

const newAddStatements = unitEntries.map(([id, data]) => {
  const rowsStr = JSON.stringify(data.rows, null, 1).replace(/\n\s*/g, '');
  return `add('${id}', ${JSON.stringify(data.title)}, ${rowsStr});`;
}).join('\n');

const updatedContent = content.replace(targetMarker, `// Bespoke 108 Curriculum comparison tables for 100% individualization (188/188 units)\n${newAddStatements}\n\n${targetMarker}`);

fs.writeFileSync(teachingPath, updatedContent, 'utf8');
console.log(`Successfully updated ${teachingPath}!`);
