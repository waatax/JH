// Every card and SVG is grounded in the same authored table row.
export function buildExplicitKnowledgeForUnit(u) {
  return groundedKnowledge(u,teachingTables[u.id],subjectThemes[u.subject] || subjectThemes.math,getKnowledgeNode(u.id),unitById);
}

