import fs from 'node:fs';
import { units } from '../dist/curriculum.js';
import { officialAlignment } from '../dist/official-alignment-data.js';

const read = name => JSON.parse(fs.readFileSync(new URL('../dist/' + name, import.meta.url), 'utf8'));
const { questions } = read('cap-bank.json');
const { books } = read('alignment-data.json');
const schoolPlans = JSON.parse(fs.readFileSync(new URL('../docs/workshop-school-plans.json',import.meta.url),'utf8'));

// Explicit selections by unit number. Each reference names a real choice question.
// A dash means the authored practice stands alone for this topic.
const references = {
  math: '114.15 114.18 115.8 114.14 115.1,114.4 115.10 114.19 114.6 114.2 115.3 113.10 115.9 114.9 115.12 112.8 115.21 113.21 113.12 115.4 114.22 114.25 113.5 115.15 115.18 115.19 112.3 -',
  chinese: '113.3 115.8 111.41 111.1 115.3 115.23 115.4 115.5 - - - 115.16,113.11 111.37 - - -',
  english: '- 115.19 115.17 112.2 112.13 115.25 - - 112.6 112.4 - 115.10 - 112.14 115.11 114.25',
  biology: '115.6 115.24 115.39 114.12 115.13 112.14 113.41 115.45 115.11 113.30 115.25 115.21 115.10 114.36',
  physics: '114.2,115.18 115.16 115.5 115.30 115.41 114.47 115.7 115.33 115.32 114.18 113.26 115.35 113.13 113.36 112.19',
  chemistry: '114.4 114.17 114.32 115.36 113.17 115.50 115.12 113.11 112.3 115.40 113.19 - 115.48 113.37',
  earth: '114.15 115.4 114.13 115.14 115.17 114.54 112.10 115.26 115.34 115.15 115.8 113.24',
  history: '111.19 115.9 115.32 111.5 115.20 115.19 115.6 111.52 115.30 115.33 114.50 115.6 111.44 111.37 114.23',
  geography: '115.28 115.1 113.51 115.2 115.3 113.29 115.16 114.17 - 113.49 114.16 - -',
  civics: '115.10 114.24 115.35 113.45 111.36 115.48 113.10 112.42 114.13 115.36 115.37 -'
};
// Climate change is tested in the social paper as well as in natural science.
const overrides = { 'earth-6': ['114-social-54'] };
const paperOf = { biology:'science', physics:'science', chemistry:'science', earth:'science',
  geography:'social', history:'social', civics:'social' };
const sourceById = new Map(questions.filter(q => q.kind === 'choice').map(q => [q.id, q]));
const norm = code => code.normalize('NFKC').trim();
const unitsById = {};
for (const unit of units) {
  const { id, subject } = unit;
  const index = Number(id.split('-').at(-1)) - 1;
  const series = references[subject]?.split(' ');
  if (series && !series[index]) throw new Error('Missing source decision for ' + id);
  const refs = series?.[index];
  const ids = overrides[id] || (!refs || refs === '-' ? [] : refs.split(',').map(ref => {
    const [year, number] = ref.split('.');
    return [year, paperOf[subject] || subject, number].join('-');
  }));
  const exams = ids.map(qid => {
    const q = sourceById.get(qid);
    if (!q?.officialObjective || !q.page) throw new Error('Check paper and question: ' + qid);
    return { id: q.id, year: q.year, subject: q.subject, number: q.number, page: q.page,
      objective: q.officialObjective };
  });
  const codes = new Set(officialAlignment[id].refs.filter(r => r.kind === '學習內容').map(r => norm(r.code)));
  const plans = [];
  for (const publisher of ['康軒','翰林','南一']) {
    const candidates = [];
    for (const book of books.filter(b => b.publisher === publisher && b.subjectIds?.includes(subject) && b.sourceUrl?.startsWith('https://'))) {
      for (const c of book.chapters) {
        const direct = !!c.unitIds?.includes(id);
        const shared = (c.codes || []).map(norm).filter(code => codes.has(code));
        if (!direct && !shared.length) continue;
        candidates.push({ direct, codes: shared, title: c.lesson.trim(), year: book.schoolYear,
          grade: book.grade, term: book.term, publisher, url: book.sourceUrl });
      }
    }
    candidates.sort((a,b) => Number(b.direct)-Number(a.direct) || b.codes.length-a.codes.length ||
      b.year-a.year || Math.abs(a.grade-unit.grade)-Math.abs(b.grade-unit.grade) || a.title.length-b.title.length);
    if (candidates.length) plans.push(candidates[0]);
    const matches = schoolPlans.filter(p=>p.publisher===publisher)
      .map(p=>({plan:p,hit:p.hits.find(([unitId])=>unitId===id)})).filter(m=>m.hit)
      .sort((a,b)=>Math.abs(a.plan.grade-unit.grade)-Math.abs(b.plan.grade-unit.grade) ||
        b.plan.year-a.plan.year || a.hit[1]-b.hit[1]);
    if (matches.length) {
      const {plan,hit:[,page,keyword]}=matches[0];
      plans.push({publisher,year:plan.year,grade:plan.grade,term:plan.term,title:keyword,
        school:plan.school,page,url:plan.url+'#page='+page,direct:false,codes:[]});
    }
  }
  unitsById[id] = { exams, plans };
}
fs.writeFileSync(new URL('../dist/workshop-sources.js', import.meta.url),
  '// Generated by scripts/build-workshop-sources.mjs\nexport const workshopSources = ' + JSON.stringify(unitsById,null,2) + ';\n');
console.log('Sourced units', Object.values(unitsById).filter(u=>u.exams.length).length,
  'Plan lookups', Object.values(unitsById).reduce((n,u)=>n+u.plans.length,0));
